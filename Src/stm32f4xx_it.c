void TIM7_IRQHandler(void)
{
  if ((TIM7->SR & TIM_SR_UIF) != 0u &&
      (TIM7->DIER & TIM_DIER_UIE) != 0u) {
    TIM7->SR = ~TIM_SR_UIF; /* RC_W0: clear only the serviced update flag. */
    test_stepper_timer_irq();
  }
}

