/*
 * 初学者导读：这里是硬件中断入口，名字由启动文件中的中断向量表指定。
 * 串口收字节时进入相应 IRQHandler，再调用 HAL_UART_IRQHandler 处理标志与数据。
 * HAL 在收满已申请的字节数后调用 App/robot.c 的 HAL_UART_RxCpltCallback。
 * 本工程每次申请1字节，所以回调分发这一字节后还要重新申请下一字节。
 * TIM6 的中断交给 HAL_TIM_IRQHandler，最终由 main.c 的回调增加HAL毫秒计数。
 */

static void fault_outputs_off(void)
{
  GPIOC->BSRR = (uint32_t)GPIO_PIN_8 << 16u;   /* 电机 STBY=0 */
  GPIOA->BSRR = (uint32_t)GPIO_PIN_15 << 16u;  /* 激光=0 */
}

